#----- LEARN ABOUT LABELS ------

def percentage_table(arr):
    total = len(arr)
    freq = Counter(arr)
    table = [(num, (count / total) * 100) for num, count in freq.items()]
    table.sort(key=lambda x: -x[1])
    return table

arr = mylabels
for num, perc in percentage_table(arr):
    print(f"{num}: {perc:.2f}%")


