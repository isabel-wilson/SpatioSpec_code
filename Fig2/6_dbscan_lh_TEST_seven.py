# This code is partly based on https://github.com/eren-ck/st_dbscan
# Plots all data points for all subjects and timepoints, coloured by label
def plot(data, labels, savedir = f"{base_dir}/dbscan/" + filename + ".png"):
    fig = plt.figure()
    ax = fig.add_subplot(1, 2, 2, projection='3d')

    colors = ["#F80606",'#1f78b4','#33a02c','#ff7f00','#6a3d9a','#b2df8a','#fb9a99','#a6cee3','#fdbf6f','#cab2d6',]
    #colors = ['#00000000','#00000000','#00000000','#ff7f00'] 
    #colors= ['#00000000','#00000000','#33a02c']

    # For every label: 
    # Choose a colour for the label
    # Pick out all the rows in the data that have this label
    # Plot everything for this label
    # Move on to next label
    for i in range(-1, len(set(labels))):
        if i == -1:
            col = [0, 0, 0, 1]
        else:
            col = colors[i % len(colors)]
        
        clust = data[np.where(labels==i)]
        
        ax.scatter(xs = clust[:,0], ys = clust[:,1], zs = clust[:,2], c=[col], s = 2, marker = '.')

    ax.set_zlabel("z (up)")
    ax.set_xlabel("x (right), on lh")
    ax.set_ylabel("y (front)")
    # https://matplotlib.org/stable/api/toolkits/mplot3d/view_angles.html
    #ax.view_init(elev=30, azim=-80, roll=0)

    # Add a freesurfer brain on the side to be helpful: 
    coords, faces = mne.read_surface("C:/meg/params/fs_subjects/fsaverage/surf/lh.inflated")
    sulc = fs.read_morph_data("C:/meg/params/fs_subjects/fsaverage/surf/lh.sulc")
    ax2 = fig.add_subplot(1, 2, 1, projection='3d')
    ax2.scatter(coords[:, 0], coords[:, 1], coords[:, 2], c=sulc, cmap='Greys', s=0.2)
    ax2.axis('off')

    fig.tight_layout()
    fig.savefig(savedir, dpi=300, bbox_inches="tight", pad_inches=1)

plot(data[:, 1:], mylabels)





