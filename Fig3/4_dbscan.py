                df_scores.loc[len(df_scores)] = [a, b, c, score, len(labels[mask])/len(data_normed), most_frequent_fraction(labels)[0], most_frequent_fraction(labels)[1], most_frequent_fraction(labels)[2]]

                print("Score: " + str(score))

