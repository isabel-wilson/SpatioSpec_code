    ax2.axis('off')
    ax2.set_xlim(-40, 40)
    ax2.set_ylim(-100, 100)
    ax2.set_zlim(-75, 75)
    if hemi == "rh":
        ax2.view_init(azim=250)
    
    fig.tight_layout()
